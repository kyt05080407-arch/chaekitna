// 옮겨 적는 방법이 여러 가지인 이름은 책마다 keys로 따로 적는다.
export function keysOf(author) {
  if (!author) return [];
  const first = author
    .split(/\s*[,·]\s*/)[0]
    .replace(/\s*(외|엮음|지음|편)$/, '')
    .trim();
  if (!first) return [];
  const words = first.split(/\s+/).filter((w) => !/^[A-Z.]+$/.test(w));
  return words.length ? [words[words.length - 1]] : [];
}

