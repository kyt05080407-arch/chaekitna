// 이름 뒤 '이/가' (받침이 있으면 '이'). 영문은 읽는 소리로: RM → 알엠 → '이'
export function subjectJosa(name) {
  const last = String(name).trim().slice(-1);
  const code = last.charCodeAt(0);
  if (code >= 0xac00 && code <= 0xd7a3) return (code - 0xac00) % 28 ? '이' : '가';
  return /[lmnr]/i.test(last) ? '이' : '가';
}

function toBook(raw, no) {
  const keys = raw.keys || keysOf(raw.author);
  const book = {
    no,
    ...(raw.field ? { field: raw.field } : {}),
    title: raw.title,
    author: raw.author || '',
    queries: raw.queries || [raw.title],
    authorKeys: keys,
    src: raw.src,
    from: raw.from,
  };
  if (raw.note) book.note = raw.note;
  if (!SOURCES[raw.src]) throw new Error(`출처가 없어요: ${raw.src} (${raw.title})`);
  return book;
}

// 목록에 쓰인 출처만 골라 붙인다
function usedSources(books) {
  const ids = [...new Set(books.map((x) => x.src))];
  return Object.fromEntries(ids.map((id) => [id, SOURCES[id]]));
}

export function buildShelves() {
  const majors = MAJORS.map((m) => {
    const books = m.books.map((raw, i) => toBook(raw, i + 1));
    return {
      id: m.id,
      group: 'major',
      title: m.title,
      short: m.short,
      icon: m.icon,
      description: m.description,
      ...(m.fields ? { fields: m.fields } : {}),
      sources: usedSources(books),
      books,
    };
  });
  const stars = PEOPLE.map((p) => {
    const books = p.books.map((raw, i) => toBook(raw, i + 1));
    return {
      id: `star-${p.id}`,
      group: 'star',
      title: `${p.name}의 책장`,
      short: p.name,
      person: { name: p.name, team: p.team, kind: p.kind },
      description: `${p.name}(${p.team})${subjectJosa(p.name)} 추천했거나 읽은 것으로 알려진 책이에요. 책을 누르면 어디서 추천했는지와 출처 기사가 보여요.`,
      sources: usedSources(books),
      books,
    };
  });
  return [...majors, ...stars];
}

